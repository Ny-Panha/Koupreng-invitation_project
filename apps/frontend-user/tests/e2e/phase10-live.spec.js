const fixtureFile = process.env.PHASE10_BROWSER_FIXTURES;
test.skip(!fixtureFile, 'Requires explicit fictional credentials for the owned loopback disposable environment.');

test('real Settings save/reload shares canonical Studio values and rejects a stale writer', async ({ page }) => {
  const fixture = JSON.parse(await readFile(fixtureFile, 'utf8'));
  expect(fixture.email).toMatch(/^phase10-browser-.*@example\.test$/);
  await page.route('**/api/**', route => new URL(route.request().url()).origin === 'http://127.0.0.1:8189' ? route.continue() : route.abort());
  await page.addInitScript(() => localStorage.setItem('koupreng.lang','en'));
  await page.goto('/login'); await page.locator('input[autocomplete="username"]').fill(fixture.email);
  await page.getByLabel('Password', { exact: true }).fill(fixture.password);
  const login = page.waitForResponse(response => response.url().endsWith('/api/auth/login') && response.request().method() === 'POST');
  await page.getByRole('button', { name: /^(Sign In|Login)$/ }).click();
  const auth = await (await login).json(); const headers = { Authorization: `Bearer ${auth.accessToken}` };
  const api = `http://127.0.0.1:8189/api/v1/invitations/${fixture.eventId}`;
  await page.goto(`/app/events/${fixture.eventId}/settings`);
  await page.locator('#event-title').fill('Phase 10 canonical Settings title');
  await page.getByLabel('RSVP deadline', { exact: true }).fill('2027-12-01');
  await page.getByRole('button', { name: 'Save details', exact: true }).click();
  await expect(page.getByText('Saved to event', { exact: true })).toBeVisible();
  await page.reload(); await expect(page.locator('#event-title')).toHaveValue('Phase 10 canonical Settings title');
  await expect(page.locator('#settings-rsvp-deadline')).toHaveValue('2027-12-01');
  await page.getByRole('link', { name: 'Open invitation Studio', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Main Title', exact: true })).toHaveValue('Phase 10 canonical Settings title');
  await page.goto(`/app/events/${fixture.eventId}/settings`);
  await expect(page.locator('#event-title')).toHaveValue('Phase 10 canonical Settings title');
  const latest = (await (await page.request.get(api, { headers })).json()).data;
  const keys = ['title','templateId','eventType','groomName','brideName','hostName','partnerName','eventDate','eventTime','venueName','venueAddress','googleMapUrl','languageMode','visibility','contentJson','rsvpDeadline'];
  const concurrent = await page.request.put(api, { headers, data: { ...Object.fromEntries(keys.map(key => [key, latest[key]])), title: 'Concurrent authoritative edit', expectedUpdatedAt: latest.updatedAt } });
  expect(concurrent.status()).toBe(200);
  await page.locator('#event-title').fill('Retained stale Settings draft');
  await page.getByRole('button', { name: 'Save details', exact: true }).click();
  await expect(page.getByText(/Another editor saved a newer version/)).toBeVisible();
  await expect(page.locator('#event-title')).toHaveValue('Retained stale Settings draft');
  await expect(page.getByRole('button', { name: 'Save details', exact: true })).toBeDisabled();
  expect((await (await page.request.get(api, { headers })).json()).data.title).toBe('Concurrent authoritative edit');
});

