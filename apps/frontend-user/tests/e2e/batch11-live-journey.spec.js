import { expect, test } from "@playwright/test";
import { readFile } from "node:fs/promises";
import process from "node:process";

test.skip(!process.env.BATCH11_BROWSER_FIXTURES, "Requires the disposable MySQL harness; no live accounts or mocked backend.");
// Personalized URLs and disposable credentials must never enter Playwright traces.
test.use({ trace: "off", screenshot: "off", video: "off" });

test("real owner UI publish, guest RSVP, scanner and admin report share persistent identity", async ({ page, browser }) => {
  test.setTimeout(150_000);
  const fixtures = JSON.parse(await readFile(process.env.BATCH11_BROWSER_FIXTURES, "utf8"));
  await page.addInitScript(() => localStorage.setItem("koupreng.lang", "en"));
  await page.goto("/login");
  await page.locator('input[autocomplete="username"]').fill(fixtures.owner.email);
  await page.getByLabel("Password", { exact: true }).fill(fixtures.owner.password);
  const login = page.waitForResponse(response => response.url().endsWith("/auth/login") && response.request().method() === "POST");
  await page.locator('.auth-form button[type="submit"]').click();
  const token = (await (await login).json()).accessToken;
  await expect(page).toHaveURL(/\/app\/events/);
  await page.goto("/app/events/new");
  await page.getByRole("button", { name: "Birthday", exact: true }).click();
  const title = `Batch11 browser ${Date.now()}`;
  await page.getByLabel("Event title", { exact: false }).fill(title);
  await page.getByLabel("Celebrant name", { exact: false }).fill("Fictional Batch 11 host");
  await page.getByLabel("Event date", { exact: false }).fill("2027-01-10");
  await page.getByLabel("Event time", { exact: false }).fill("17:30");
  await page.getByRole("textbox", { name: "Venue", exact: true }).fill("Fictional venue");
  await page.getByLabel("Address (optional)").fill("Fictional Phnom Penh address");
  await page.getByRole("button", { name: /^Select .*Event Essential$/ }).click();
  await page.getByRole("button", { name: "Create event", exact: true }).click();
  await expect(page).toHaveURL(/\/app\/events\/\d+\/invitation\?mode=guided/);
  const eventId = page.url().match(/events\/(\d+)/)[1];
  await page.getByLabel("English Invitation message", { exact: true }).fill("Please join this fictional Batch 11 event.");
  await page.getByRole("button", { name: "Save details", exact: true }).click();
  await expect(page.getByText("Saved to event", { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByLabel("English Event title", { exact: true })).toHaveValue(title);
  const ownerHeaders = { Authorization: `Bearer ${token}` };
  const guestResponse = await page.request.post(`/api/v1/invitations/${eventId}/guests`, { headers: ownerHeaders, data: { guestName: "Batch 11 fictional guest", seatCount: 2 } });
  expect(guestResponse.status()).toBe(201);
  const guest = (await guestResponse.json()).data;
  await page.getByRole("button", { name: "Review publication", exact: true }).click();
  await page.getByRole("button", { name: "Confirm publication", exact: true }).click();
  const view = page.getByRole("link", { name: "View invitation", exact: true });
  await expect(view).toBeVisible();
  const slug = new URL(await view.getAttribute("href"), page.url()).pathname.split("/").at(-1);
  const guestContext = await browser.newContext();
  try {
    const guestPage = await guestContext.newPage();
    await guestPage.goto(`http://127.0.0.1:4175/i/${slug}?token=${encodeURIComponent(guest.inviteToken)}`);
    await expect(guestPage.getByRole("heading", { name: title, exact: true })).toBeVisible();
    const rsvp = guestPage.waitForResponse(response => response.url().includes(`/guests/${guest.inviteToken}/rsvp`) && response.request().method() === "POST");
    await guestPage.getByRole("button", { name: "Submit RSVP", exact: true }).click();
    expect((await rsvp).status()).toBe(201);
    await guestPage.reload();
    await expect(guestPage.getByText("Batch 11 fictional guest", { exact: true }).first()).toBeVisible();
  } finally { await guestContext.close(); }
  await page.goto(`/app/events/${eventId}/check-in`);
  await page.getByLabel("QR link or token").fill(guest.inviteToken);
  const scan = page.waitForResponse(response => response.url().endsWith(`/invitations/${eventId}/check-in/scan`) && response.request().method() === "POST");
  await page.locator("form.guest-form button[type='submit']").click();
  expect((await scan).status()).toBe(200);
  const summary = await page.request.get(`/api/v1/invitations/${eventId}/check-in/summary`, { headers: ownerHeaders });
  expect((await summary.json()).data).toMatchObject({ checkedIn: 1, attendingCheckedIn: 1 });
  await page.goto("http://127.0.0.1:4176/login");
  await page.evaluate(() => localStorage.setItem("koupreng.admin.lang", "en"));
  await page.reload();
  await page.locator("#identifier").fill(fixtures.admin.email);
  await page.locator("#password").fill(fixtures.admin.password);
  const adminLogin = page.waitForResponse(response => response.url().endsWith("/auth/login") && response.request().method() === "POST");
  await page.locator('button[type="submit"]').click();
  const adminToken = (await (await adminLogin).json()).accessToken;
  await expect(page).toHaveURL(/4176\/dashboard/);
  const report = await page.request.get(`/api/v1/admin/reports/management/invitations?search=${encodeURIComponent(title)}`, { headers: { Authorization: `Bearer ${adminToken}` } });
  expect(report.status()).toBe(200);
  expect((await report.json()).data.rows).toEqual([expect.objectContaining({ id: Number(eventId), title, guestCount: 1, rsvpCount: 1, checkedInCount: 1 })]);
  await page.goto(`http://127.0.0.1:4176/reports?report=invitations&search=${encodeURIComponent(title)}`);
  await expect(page.getByRole("heading", { name: "Reports & Analytics", exact: true })).toBeVisible();
});
