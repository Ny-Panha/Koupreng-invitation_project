import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import process from 'node:process';

const fixtureFile = process.env.PHASE8_BROWSER_FIXTURES;
test.skip(!fixtureFile, 'Requires explicit private credentials for the owned loopback disposable environment.');

test('actual create → multi-day Studio → SQL-backed reload → publish → public calendar export', async ({ page }, info) => {
  const fixture = JSON.parse(await readFile(fixtureFile, 'utf8'));
  expect(fixture.plan.code).toMatch(/^P8-BROWSER-/);
  await page.addInitScript(() => localStorage.setItem('koupreng.lang', 'en'));
  await page.goto('/login');
  await page.locator('input[autocomplete="username"]').fill(fixture.owner.email);
  await page.getByLabel('Password', { exact: true }).fill(fixture.owner.password);
  await page.getByRole('button', { name: /^(Sign In|Login)$/ }).click();
  await expect(page).toHaveURL(/\/app\/events/);
  await page.goto('/app/events/new'); await page.getByRole('button', { name: 'Wedding', exact: true }).click();
  await page.getByLabel('Event title', { exact: false }).fill(`Phase 8 fictional wedding ${Date.now()}`);
  await page.getByLabel('Groom name', { exact: false }).fill('Fictional Dara');
  await page.getByLabel('Bride name', { exact: false }).fill('Fictional Sophea');
  await page.getByLabel('Event date', { exact: false }).fill('2027-12-05');
  await page.getByLabel('Event time', { exact: false }).fill('17:30');
  await page.getByRole('textbox', { name: 'Venue', exact: true }).fill('Fictional celebration garden');
  await page.getByLabel('Address (optional)').fill('Fictional Phnom Penh address');
  await page.getByRole('button', { name: /^Select .*Khmer Celestial$/ }).click();
  await page.getByRole('button', { name: 'Create event', exact: true }).click();
  await expect(page).toHaveURL(/\/app\/events\/\d+\/invitation\?mode=guided/);
  await expect(page.getByRole('navigation', { name: 'Creation steps' })).toBeVisible();
  const id = page.url().match(/events\/(\d+)/)[1];
  await page.getByRole('button', { name: /Design & content/ }).click(); await page.getByRole('button', { name: 'Program', exact: true }).click();
  for (let index = 1; index <= 3; index++) {
    await page.getByRole('button', { name: 'Add program day' }).click();
    const day = page.getByRole('group', { name: `Day ${index}`, exact: true });
    await day.getByRole('button', { name: 'Add ceremony' }).click();
    await day.getByLabel('Start time', { exact: false }).fill('07:00');
    await day.getByLabel('Ceremony / Khmer', { exact: true }).fill(`ពិធីថ្ងៃទី ${index}`);
    await day.getByLabel('Ceremony in English', { exact: true }).fill(`Actual saved ceremony ${index}`);
  }
  await page.getByRole('button', { name: 'Move day 3 up' }).click();
  const write = page.waitForResponse(response => response.request().method() === 'PUT' && new URL(response.url()).pathname === `/api/v1/invitations/${id}`);
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  const saved = (await (await write).json()).data; expect(JSON.parse(saved.contentJson).programDays).toHaveLength(3);
  await expect(page.locator('.studio-save-status')).toHaveAttribute('data-phase', 'saved');
  await page.reload(); await page.getByRole('button', { name: 'Advanced editor', exact: true }).click();
  await page.getByRole('button', { name: 'Schedule', exact: true }).click();
  await expect(page.getByRole('group', { name: 'Day 3', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Save the date & calendar', exact: true }).click();
  await page.getByLabel('Event timezone', { exact: true }).fill('America/New_York');
  await page.getByLabel('Show calendar', { exact: true }).check(); await page.getByLabel('Show Add to Calendar', { exact: true }).check();
  await page.getByRole('button', { name: 'Save', exact: true }).click(); await expect(page.locator('.studio-save-status')).toHaveAttribute('data-phase', 'saved');
  await page.reload();
  await page.goto(`/app/events/${id}/settings`);
  await page.getByRole('combobox', { name: 'Invitation visibility', exact: true }).selectOption('PUBLIC');
  await page.getByRole('button', { name: 'Save details', exact: true }).click();
  await expect(page.getByText('Saved to event', { exact: true })).toBeVisible();
  await page.goto(`/app/events/${id}/invitation?mode=guided`);
  await page.getByRole('button', { name: 'Guided creation', exact: true }).click();
  await page.getByRole('button', { name: /Publish & share/ }).click();
  await page.getByRole('button', { name: 'Review publication', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm publication', exact: true }).click();
  const publicLink = page.getByRole('link', { name: 'View invitation', exact: true }); await expect(publicLink).toBeVisible();
  const url = await publicLink.getAttribute('href');
  await page.goto(url); await page.getByRole('button', { name: /^(Open invitation|បើកសំបុត្រអញ្ជើញ)$/ }).click();
  await expect(page.getByText('Actual saved ceremony 3', { exact: true })).toBeVisible();
  await expect(page.locator('.kp-calendar-event')).toHaveAttribute('datetime', '2027-12-05');
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Add to calendar', exact: true }).click();
  await (await download).saveAs(info.outputPath('actual-celebration.ics'));
  await page.locator('.kp-save-date').screenshot({ path: info.outputPath('actual-public-save-date.png') });
  await page.locator('.kp-program').screenshot({ path: info.outputPath('actual-public-program.png') });
});
