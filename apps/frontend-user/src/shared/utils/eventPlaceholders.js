/**
 * Get event examples for a given event type and language.
 * Falls back to WEDDING if event type is not found.
 */
export function getEventExamples(eventType = 'WEDDING', lang = 'km') {
  const normType = String(eventType || 'WEDDING').toUpperCase();
  const typeConfig = EVENT_EXAMPLES[normType] || EVENT_EXAMPLES.WEDDING;
  const langKey = lang === 'en' ? 'en' : 'km';
  return typeConfig[langKey] || typeConfig.km;
}

